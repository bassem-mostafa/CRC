CRC_Status_t CRC_Initialize( CRC_t CRCx )
{
    CRC_Status_t Status = CRC_Status_Success;

    do
    {
        CRC_Trace( "%s( CRCx=%d )", __FUNCTION__, CRCx );

        if ( ( Status = CRC_Port_Initialize( CRCx ) ) != CRC_Status_Success )
        {
            break;
        }
    }
    while ( 0 );

    return Status;
}

